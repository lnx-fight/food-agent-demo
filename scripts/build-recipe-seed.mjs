import {DatabaseSync} from 'node:sqlite';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {nutritionKey} from '../nutrition-names.mjs';
import nutritionManifest from '../data/tfda/manifest.json' with {type:'json'};
import source from '../data/recipes/home-recipes.json' with {type:'json'};

const db=new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
const root=new URL('../',import.meta.url);
for(const file of ['0007_tfda_schema.sql',...nutritionManifest.snapshotMigrations,'0009_tfda_activate.sql','0010_recipe_schema.sql'])db.exec(readFileSync(new URL('migrations/'+file,root),'utf8'));
const quote=value=>"'"+String(value).replaceAll("'","''")+"'";
const literal=value=>typeof value==='number'?String(value):quote(value);
const insert=(table,columns,values)=>`INSERT INTO ${table}(${columns.join(',')}) VALUES(${values.map(literal).join(',')});`;
const metrics={kcal:'kcal',protein:'protein',fat:'fat',carbs:'carbs',fiber:'fiber',sodiumMg:'sodium_mg',sugar:'sugar',saturatedFat:'saturated_fat'};
const sql=['-- Generated by npm run recipes:build; do not edit. Source and editorial additions are retained in provenance.'];
assert.equal(source.recipes.length,20);
assert.equal(new Set(source.recipes.map(recipe=>recipe.id)).size,20);
for(const recipe of source.recipes){
  assert.ok(recipe.name&&recipe.steps.length>=2&&recipe.servings===1);
  assert.ok(recipe.ingredients.some(item=>item.role==='main'));
  assert.ok(recipe.provenance.excerpt&&recipe.provenance.pdfPage===recipe.provenance.printedPage+2);
  const seen=new Set(),foodRows=[];
  for(const item of recipe.ingredients){
    assert.ok(Number.isFinite(item.grams)&&item.grams>0&&item.grams<=1000,recipe.name);
    assert.ok(!seen.has(item.foodId));seen.add(item.foodId);
    const food=db.prepare('SELECT * FROM nutrition_foods WHERE food_id=?').get(item.foodId);
    assert.ok(food,`${recipe.name}: ${item.foodId}`);
    for(const key of ['kcal','protein','fat','carbs'])assert.ok(Number.isFinite(food[key]),`${recipe.name}: ${item.name} ${key} missing`);
    foodRows.push(food);
  }
  const nutrition=Object.fromEntries(Object.entries(metrics).map(([key,column])=>[key,foodRows.some(food=>food[column]==null)?null:+foodRows.reduce((sum,food,i)=>sum+food[column]*recipe.ingredients[i].grams/100,0).toFixed(2)]));
  const aliases=recipe.name.includes('西红柿')?[recipe.name.replace('西红柿','番茄'),recipe.name.replace('西红柿炒蛋','番茄炒鸡蛋')]:[];
  const searchText=nutritionKey([recipe.name,...aliases,...recipe.ingredients.map(item=>item.name)].join(' '));
  const provenance={...recipe.provenance,sourceTitle:source.sourceTitle,publisher:source.publisher,sourceUrl:source.sourceUrl,sourceSha256:source.sourceSha256,nutritionSource:'TFDA',nutritionRelease:nutritionManifest.release,calculation:'sum(raw_edible_or_as_sold_grams * TFDA_per100g / 100); no cooking retention or yield factor',stepsOrigin:'editorial',waterOrigin:'editorial'};
  sql.push(insert('recipes',['id','name','search_text','servings','portion_type','minutes','water_ml','steps','allergens','nutrition','provenance','seed_version','created_at'],[recipe.id,recipe.name,searchText,recipe.servings,recipe.portionType,recipe.minutes,recipe.waterMl,JSON.stringify(recipe.steps),JSON.stringify(recipe.allergens),JSON.stringify(nutrition),JSON.stringify(provenance),source.version,source.retrievedOn]));
  recipe.ingredients.forEach((item,index)=>sql.push(insert('recipe_ingredients',['recipe_id','position','name','food_id','grams','role','quantity_origin','food_state'],[recipe.id,index,item.name,item.foodId,item.grams,item.role,item.quantityOrigin,item.state])));
}
const {recipes,...manifest}=source;
sql.push(insert('recipe_seed_batches',['version','recipe_count','manifest'],[source.version,20,JSON.stringify(manifest)]));
const output=sql.join('\n')+'\n';
db.exec(output);
assert.equal(db.prepare('SELECT COUNT(*) n FROM recipes').get().n,20);
assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
const path=new URL('../migrations/0011_home_recipes.sql',import.meta.url);
if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8'),output,'Recipe migration is stale: run npm run recipes:build');
else writeFileSync(path,output);
db.close();
console.log(`20 recipes validated; ${process.argv.includes('--check')?'verified':'wrote'} ${fileURLToPath(path)}`);
